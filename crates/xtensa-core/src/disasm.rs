pub fn ur_name(n: u32) -> String {
    match n {
        231 => "threadptr".into(),
        232 => "fcr".into(),
        233 => "fsr".into(),
        _ => format!("ur{}", n),
    }
}

/// Disassemble one instruction located at `pc` whose raw bytes (little endian) are `w`.
/// Returns (text, length).
pub fn disasm(pc: u32, w: u32) -> (String, u8) {
    let i = decode(w);
    (format_insn(pc, &i), i.len)
}

pub fn format_insn(pc: u32, i: &Insn) -> String {
    use Op::*;
    let a = |n: u8| format!("a{}", n);
    let f = |n: u8| format!("f{}", n);
    let b = |n: u8| format!("b{}", n);
    let (r, s, t) = (i.r, i.s, i.t);
    let n = i.len == 2;
    let br = |off: i32| format!("0x{:08x}", pc.wrapping_add(4).wrapping_add(off as u32));
    match i.op {
        Ill => if n { "ill.n".into() } else { "ill".into() },
        Nop => {
            if n {
                "nop.n".into()
            } else {
                match (i.r, i.t) {
                    (2, 0) => "isync".into(),
                    (2, 1) => "rsync".into(),
                    (2, 2) => "esync".into(),
                    (2, 3) => "dsync".into(),
                    (2, 8) => "excw".into(),
                    (2, 0xC) => "memw".into(),
                    (2, 0xD) => "extw".into(),
                    _ => "nop".into(),
                }
            }
        }
        Break => format!("break {}, {}", s, t),
        BreakN => format!("break.n {}", s),
        Syscall => "syscall".into(),
        Simcall => "simcall".into(),
        Rsil => format!("rsil {}, {}", a(t), s),
        Waiti => format!("waiti {}", s),
        Rfe => "rfe".into(),
        Rfue => "rfue".into(),
        Rfde => "rfde".into(),
        Rfwo => "rfwo".into(),
        Rfwu => "rfwu".into(),
        Rfi => format!("rfi {}", s),
        Rfme => "rfme".into(),
        Ret => "ret".into(),
        RetN => "ret.n".into(),
        Retw => "retw".into(),
        RetwN => "retw.n".into(),
        Jx => format!("jx {}", a(s)),
        Callx0 => format!("callx0 {}", a(s)),
        Callx4 => format!("callx4 {}", a(s)),
        Callx8 => format!("callx8 {}", a(s)),
        Callx12 => format!("callx12 {}", a(s)),
        Movsp => format!("movsp {}, {}", a(t), a(s)),
        And => format!("and {}, {}, {}", a(r), a(s), a(t)),
        Or => {
            if n {
                format!("mov.n {}, {}", a(r), a(s))
            } else if s == t {
                format!("mov {}, {}", a(r), a(s))
            } else {
                format!("or {}, {}, {}", a(r), a(s), a(t))
            }
        }
        Xor => format!("xor {}, {}, {}", a(r), a(s), a(t)),
        Add => format!("add{} {}, {}, {}", if n { ".n" } else { "" }, a(r), a(s), a(t)),
        Addx2 => format!("addx2 {}, {}, {}", a(r), a(s), a(t)),
        Addx4 => format!("addx4 {}, {}, {}", a(r), a(s), a(t)),
        Addx8 => format!("addx8 {}, {}, {}", a(r), a(s), a(t)),
        Sub => format!("sub {}, {}, {}", a(r), a(s), a(t)),
        Subx2 => format!("subx2 {}, {}, {}", a(r), a(s), a(t)),
        Subx4 => format!("subx4 {}, {}, {}", a(r), a(s), a(t)),
        Subx8 => format!("subx8 {}, {}, {}", a(r), a(s), a(t)),
        Neg => format!("neg {}, {}", a(r), a(t)),
        Abs => format!("abs {}, {}", a(r), a(t)),
        Ssr => format!("ssr {}", a(s)),
        Ssl => format!("ssl {}", a(s)),
        Ssa8l => format!("ssa8l {}", a(s)),
        Ssa8b => format!("ssa8b {}", a(s)),
        Ssai => format!("ssai {}", i.imm),
        Rer => format!("rer {}, {}", a(t), a(s)),
        Wer => format!("wer {}, {}", a(t), a(s)),
        Rotw => format!("rotw {}", i.imm),
        Nsa => format!("nsa {}, {}", a(t), a(s)),
        Nsau => format!("nsau {}, {}", a(t), a(s)),
        TlbRead | TlbNop => format!("tlb/cache-op 0x{:06x}", i.raw()),
        Slli => format!("slli {}, {}, {}", a(r), a(s), i.imm),
        Srai => format!("srai {}, {}, {}", a(r), a(t), i.imm),
        Srli => format!("srli {}, {}, {}", a(r), a(t), i.imm),
        Xsr => format!("xsr {}, {}", a(t), sr_name(i.imm as u32)),
        Src => format!("src {}, {}, {}", a(r), a(s), a(t)),
        Srl => format!("srl {}, {}", a(r), a(t)),
        Sll => format!("sll {}, {}", a(r), a(s)),
        Sra => format!("sra {}, {}", a(r), a(t)),
        Mul16u => format!("mul16u {}, {}, {}", a(r), a(s), a(t)),
        Mul16s => format!("mul16s {}, {}, {}", a(r), a(s), a(t)),
        Andb => format!("andb {}, {}, {}", b(r), b(s), b(t)),
        Andbc => format!("andbc {}, {}, {}", b(r), b(s), b(t)),
        Orb => format!("orb {}, {}, {}", b(r), b(s), b(t)),
        Orbc => format!("orbc {}, {}, {}", b(r), b(s), b(t)),
        Xorb => format!("xorb {}, {}, {}", b(r), b(s), b(t)),
        Any4 => format!("any4 {}, {}", b(t), b(s)),
        All4 => format!("all4 {}, {}", b(t), b(s)),
        Any8 => format!("any8 {}, {}", b(t), b(s)),
        All8 => format!("all8 {}, {}", b(t), b(s)),
        Mull => format!("mull {}, {}, {}", a(r), a(s), a(t)),
        Muluh => format!("muluh {}, {}, {}", a(r), a(s), a(t)),
        Mulsh => format!("mulsh {}, {}, {}", a(r), a(s), a(t)),
        Quou => format!("quou {}, {}, {}", a(r), a(s), a(t)),
        Quos => format!("quos {}, {}, {}", a(r), a(s), a(t)),
        Remu => format!("remu {}, {}, {}", a(r), a(s), a(t)),
        Rems => format!("rems {}, {}, {}", a(r), a(s), a(t)),
        Rsr => format!("rsr {}, {}", a(t), sr_name(i.imm as u32)),
        Wsr => format!("wsr {}, {}", a(t), sr_name(i.imm as u32)),
        Sext => format!("sext {}, {}, {}", a(r), a(s), i.imm),
        Clamps => format!("clamps {}, {}, {}", a(r), a(s), i.imm),
        Min => format!("min {}, {}, {}", a(r), a(s), a(t)),
        Max => format!("max {}, {}, {}", a(r), a(s), a(t)),
        Minu => format!("minu {}, {}, {}", a(r), a(s), a(t)),
        Maxu => format!("maxu {}, {}, {}", a(r), a(s), a(t)),
        Moveqz => format!("moveqz {}, {}, {}", a(r), a(s), a(t)),
        Movnez => format!("movnez {}, {}, {}", a(r), a(s), a(t)),
        Movltz => format!("movltz {}, {}, {}", a(r), a(s), a(t)),
        Movgez => format!("movgez {}, {}, {}", a(r), a(s), a(t)),
        Movf => format!("movf {}, {}, {}", a(r), a(s), b(t)),
        Movt => format!("movt {}, {}, {}", a(r), a(s), b(t)),
        Rur => format!("rur {}, {}", a(r), ur_name(i.imm as u32)),
        Wur => format!("wur {}, {}", a(t), ur_name(i.imm as u32)),
        Extui => format!("extui {}, {}, {}, {}", a(r), a(t), i.imm & 0xFF, i.imm >> 8),
        L32e => format!("l32e {}, {}, {}", a(t), a(s), i.imm),
        S32e => format!("s32e {}, {}, {}", a(t), a(s), i.imm),
        AddS => format!("add.s {}, {}, {}", f(r), f(s), f(t)),
        SubS => format!("sub.s {}, {}, {}", f(r), f(s), f(t)),
        MulS => format!("mul.s {}, {}, {}", f(r), f(s), f(t)),
        MaddS => format!("madd.s {}, {}, {}", f(r), f(s), f(t)),
        MsubS => format!("msub.s {}, {}, {}", f(r), f(s), f(t)),
        MaddnS => format!("maddn.s {}, {}, {}", f(r), f(s), f(t)),
        DivnS => format!("divn.s {}, {}, {}", f(r), f(s), f(t)),
        ConstS => format!("const.s {}, {}", f(r), s),
        Div0S => format!("div0.s {}, {}", f(r), f(s)),
        Recip0S => format!("recip0.s {}, {}", f(r), f(s)),
        Sqrt0S => format!("sqrt0.s {}, {}", f(r), f(s)),
        Rsqrt0S => format!("rsqrt0.s {}, {}", f(r), f(s)),
        Nexp01S => format!("nexp01.s {}, {}", f(r), f(s)),
        MksadjS => format!("mksadj.s {}, {}", f(r), f(s)),
        MkdadjS => format!("mkdadj.s {}, {}", f(r), f(s)),
        AddexpS => format!("addexp.s {}, {}", f(r), f(s)),
        AddexpmS => format!("addexpm.s {}, {}", f(r), f(s)),
        RoundS => format!("round.s {}, {}, {}", a(r), f(s), t),
        TruncS => format!("trunc.s {}, {}, {}", a(r), f(s), t),
        FloorS => format!("floor.s {}, {}, {}", a(r), f(s), t),
        CeilS => format!("ceil.s {}, {}, {}", a(r), f(s), t),
        FloatS => format!("float.s {}, {}, {}", f(r), a(s), t),
        UfloatS => format!("ufloat.s {}, {}, {}", f(r), a(s), t),
        UtruncS => format!("utrunc.s {}, {}, {}", a(r), f(s), t),
        MovS => format!("mov.s {}, {}", f(r), f(s)),
        AbsS => format!("abs.s {}, {}", f(r), f(s)),
        Rfr => format!("rfr {}, {}", a(r), f(s)),
        Wfr => format!("wfr {}, {}", f(r), a(s)),
        NegS => format!("neg.s {}, {}", f(r), f(s)),
        UnS => format!("un.s {}, {}, {}", b(r), f(s), f(t)),
        OeqS => format!("oeq.s {}, {}, {}", b(r), f(s), f(t)),
        UeqS => format!("ueq.s {}, {}, {}", b(r), f(s), f(t)),
        OltS => format!("olt.s {}, {}, {}", b(r), f(s), f(t)),
        UltS => format!("ult.s {}, {}, {}", b(r), f(s), f(t)),
        OleS => format!("ole.s {}, {}, {}", b(r), f(s), f(t)),
        UleS => format!("ule.s {}, {}, {}", b(r), f(s), f(t)),
        MoveqzS => format!("moveqz.s {}, {}, {}", f(r), f(s), a(t)),
        MovnezS => format!("movnez.s {}, {}, {}", f(r), f(s), a(t)),
        MovltzS => format!("movltz.s {}, {}, {}", f(r), f(s), a(t)),
        MovgezS => format!("movgez.s {}, {}, {}", f(r), f(s), a(t)),
        MovfS => format!("movf.s {}, {}, {}", f(r), f(s), b(t)),
        MovtS => format!("movt.s {}, {}, {}", f(r), f(s), b(t)),
        Lsi => format!("lsi {}, {}, {}", f(t), a(s), i.imm),
        Ssi => format!("ssi {}, {}, {}", f(t), a(s), i.imm),
        Lsiu => format!("lsiu {}, {}, {}", f(t), a(s), i.imm),
        Ssiu => format!("ssiu {}, {}, {}", f(t), a(s), i.imm),
        Lsx => format!("lsx {}, {}, {}", f(r), a(s), a(t)),
        Lsxu => format!("lsxu {}, {}, {}", f(r), a(s), a(t)),
        Ssx => format!("ssx {}, {}, {}", f(r), a(s), a(t)),
        Ssxu => format!("ssxu {}, {}, {}", f(r), a(s), a(t)),
        L32r => {
            let addr = (pc.wrapping_add(3) & !3).wrapping_add(i.imm as u32);
            format!("l32r {}, 0x{:08x}", a(t), addr)
        }
        L8ui => format!("l8ui {}, {}, {}", a(t), a(s), i.imm),
        L16ui => format!("l16ui {}, {}, {}", a(t), a(s), i.imm),
        L16si => format!("l16si {}, {}, {}", a(t), a(s), i.imm),
        L32i => format!("l32i{} {}, {}, {}", if n { ".n" } else { "" }, a(t), a(s), i.imm),
        S8i => format!("s8i {}, {}, {}", a(t), a(s), i.imm),
        S16i => format!("s16i {}, {}, {}", a(t), a(s), i.imm),
        S32i => format!("s32i{} {}, {}, {}", if n { ".n" } else { "" }, a(t), a(s), i.imm),
        Cache => format!("cache-op {}, {}, {}", t, a(s), i.imm),
        Movi => format!("movi{} {}, {}", if n { ".n" } else { "" }, a(t), i.imm),
        L32ai => format!("l32ai {}, {}, {}", a(t), a(s), i.imm),
        Addi => format!("addi{} {}, {}, {}", if n { ".n" } else { "" }, a(t), a(s), i.imm),
        Addmi => format!("addmi {}, {}, {}", a(t), a(s), i.imm),
        S32c1i => format!("s32c1i {}, {}, {}", a(t), a(s), i.imm),
        S32ri => format!("s32ri {}, {}, {}", a(t), a(s), i.imm),
        Call0 | Call4 | Call8 | Call12 => {
            let nm = match i.op {
                Call0 => "call0",
                Call4 => "call4",
                Call8 => "call8",
                _ => "call12",
            };
            let target = (pc & !3).wrapping_add(i.imm as u32).wrapping_add(4);
            format!("{} 0x{:08x}", nm, target)
        }
        J => format!("j {}", br(i.imm)),
        Beqz => format!("beqz{} {}, {}", if n { ".n" } else { "" }, a(s), br(i.imm)),
        Bnez => format!("bnez{} {}, {}", if n { ".n" } else { "" }, a(s), br(i.imm)),
        Bltz => format!("bltz {}, {}", a(s), br(i.imm)),
        Bgez => format!("bgez {}, {}", a(s), br(i.imm)),
        Beqi => format!("beqi {}, {}, {}", a(s), B4CONST[r as usize], br(i.imm)),
        Bnei => format!("bnei {}, {}, {}", a(s), B4CONST[r as usize], br(i.imm)),
        Blti => format!("blti {}, {}, {}", a(s), B4CONST[r as usize], br(i.imm)),
        Bgei => format!("bgei {}, {}, {}", a(s), B4CONST[r as usize], br(i.imm)),
        Bltui => format!("bltui {}, {}, {}", a(s), B4CONSTU[r as usize], br(i.imm)),
        Bgeui => format!("bgeui {}, {}, {}", a(s), B4CONSTU[r as usize], br(i.imm)),
        Entry => format!("entry {}, {}", a(s), i.imm),
        Bf => format!("bf {}, {}", b(s), br(i.imm)),
        Bt => format!("bt {}, {}", b(s), br(i.imm)),
        Loop => format!("loop {}, 0x{:08x}", a(s), pc.wrapping_add(4).wrapping_add(i.imm as u32)),
        Loopnez => format!("loopnez {}, 0x{:08x}", a(s), pc.wrapping_add(4).wrapping_add(i.imm as u32)),
        Loopgtz => format!("loopgtz {}, 0x{:08x}", a(s), pc.wrapping_add(4).wrapping_add(i.imm as u32)),
        Bnone => format!("bnone {}, {}, {}", a(s), a(t), br(i.imm)),
        Beq => format!("beq {}, {}, {}", a(s), a(t), br(i.imm)),
        Blt => format!("blt {}, {}, {}", a(s), a(t), br(i.imm)),
        Bltu => format!("bltu {}, {}, {}", a(s), a(t), br(i.imm)),
        Ball => format!("ball {}, {}, {}", a(s), a(t), br(i.imm)),
        Bbc => format!("bbc {}, {}, {}", a(s), a(t), br(i.imm)),
        Bbci => format!("bbci {}, {}, {}", a(s), ((r & 1) << 4) | t, br(i.imm)),
        Bany => format!("bany {}, {}, {}", a(s), a(t), br(i.imm)),
        Bne => format!("bne {}, {}, {}", a(s), a(t), br(i.imm)),
        Bge => format!("bge {}, {}, {}", a(s), a(t), br(i.imm)),
        Bgeu => format!("bgeu {}, {}, {}", a(s), a(t), br(i.imm)),
        Bnall => format!("bnall {}, {}, {}", a(s), a(t), br(i.imm)),
        Bbs => format!("bbs {}, {}, {}", a(s), a(t), br(i.imm)),
        Bbsi => format!("bbsi {}, {}, {}", a(s), ((r & 1) << 4) | t, br(i.imm)),
        Mac16 => format!("mac16 0x{:06x}", i.raw()),
    }
}
