//! Assembler <-> disassembler agreement: for every decodable instruction word,
//! `assemble(disasm(w))` must decode to the same text.  Covers every opcode the
//! decoder knows (random sampling of the 24-bit space plus all 16-bit words).
use xtensa_core::asm::assemble_one;
use xtensa_core::{decode, disasm::format_insn, Op};

const PC: u32 = 0x4008_1000;

fn check(w: u32, failures: &mut Vec<String>, seen: &mut std::collections::HashSet<String>) {
    let i = decode(w);
    let text = format_insn(PC, &i);
    let mnemonic = text.split_whitespace().next().unwrap_or("").to_string();
    match assemble_one(&text, PC) {
        Ok(bytes) => {
            let mut w2 = 0u32;
            for (k, b) in bytes.iter().enumerate() {
                w2 |= (*b as u32) << (8 * k);
            }
            if bytes.len() != i.len as usize {
                failures.push(format!("{:06x} '{}': length {} != {}", w, text, bytes.len(), i.len));
                return;
            }
            let back = format_insn(PC, &decode(w2));
            if back != text {
                failures.push(format!("{:06x} '{}' -> {:06x} '{}'", w, text, w2, back));
            }
        }
        Err(e) => failures.push(format!("{:06x} '{}': {}", w, text, e)),
    }
    if i.op != Op::Ill {
        seen.insert(mnemonic);
    }
}

#[test]
fn every_narrow_instruction_roundtrips() {
    let mut failures = Vec::new();
    let mut seen = Default::default();
    for w in 0..0x1_0000u32 {
        if (8..=0xD).contains(&(w & 0xF)) {
            check(w, &mut failures, &mut seen);
        }
    }
    assert!(failures.is_empty(), "{} failures, e.g.\n{}", failures.len(), failures[..failures.len().min(20)].join("\n"));
}

#[test]
fn wide_instructions_roundtrip() {
    let mut failures = Vec::new();
    let mut seen = std::collections::HashSet::new();
    // xorshift sampling of the 24-bit space, plus every op0/op1/op2/r combination
    let mut x: u32 = 0x1234_5678;
    let mut words = Vec::new();
    for _ in 0..400_000 {
        x ^= x << 13;
        x ^= x >> 17;
        x ^= x << 5;
        words.push(x & 0xFF_FFFF);
    }
    for op0 in 0..8u32 {
        for op1 in 0..16u32 {
            for op2 in 0..16u32 {
                for r in 0..16u32 {
                    for st in [0u32, 0x15, 0xF0, 0x3C, 0xFF] {
                        words.push(op2 << 20 | op1 << 16 | r << 12 | st << 4 | op0);
                    }
                }
            }
        }
    }
    for w in words {
        if (8..=0xD).contains(&(w & 0xF)) {
            continue;
        }
        check(w, &mut failures, &mut seen);
    }
    assert!(failures.is_empty(), "{} failures, e.g.\n{}", failures.len(), failures[..failures.len().min(30)].join("\n"));
    // the sample reaches (nearly) every mnemonic
    assert!(seen.len() > 180, "only {} distinct mnemonics seen", seen.len());
}

/// Byte-exact agreement with LLVM's Xtensa assembler (reference generated by
/// `tests/data/gen_llvm_reference.sh`; llvm-mc is not needed to run the test).
#[test]
fn matches_llvm_mc_encodings() {
    let src = include_str!("data/llvm_check.s");
    let hex = include_str!("data/llvm_check.hex").trim();
    let want: Vec<u8> = (0..hex.len()).step_by(2).map(|i| u8::from_str_radix(&hex[i..i + 2], 16).unwrap()).collect();
    let p = xtensa_core::assemble(src, 0).expect("assemble");
    for (k, (a, b)) in p.bytes.iter().zip(want.iter()).enumerate() {
        assert_eq!(a, b, "byte {} differs (instruction near offset {}): ours {:02x} llvm {:02x}", k, k - k % 3, a, b);
    }
    assert_eq!(p.bytes.len(), want.len());
}

/// Encodings as produced by GNU as / seen in ESP-IDF firmware disassembly.
#[test]
fn known_encodings() {
    for (text, bytes) in [
        ("ret.n", vec![0x0d, 0xf0]),
        ("retw.n", vec![0x1d, 0xf0]),
        ("nop.n", vec![0x3d, 0xf0]),
        ("mov.n a7, a2", vec![0x7d, 0x02]),
        ("movi.n a2, 0", vec![0x0c, 0x02]),
        ("movi.n a3, 1", vec![0x0c, 0x13]),
        ("l32i.n a2, a1, 0", vec![0x28, 0x01]),
        ("s32i.n a2, a1, 4", vec![0x29, 0x11]),
        ("add.n a2, a2, a3", vec![0x3a, 0x22]),
        ("addi.n a2, a2, 1", vec![0x1b, 0x22]),
        ("break.n 1", vec![0x2d, 0xf1]),
        ("entry a1, 32", vec![0x36, 0x41, 0x00]),
        ("retw", vec![0x90, 0x00, 0x00]),
        ("memw", vec![0xc0, 0x20, 0x00]),
        ("rsil a2, 3", vec![0x20, 0x63, 0x00]),
        ("wsr a2, ps", vec![0x20, 0xe6, 0x13]),
        ("rsr a2, ccount", vec![0x20, 0xea, 0x03]),
        ("waiti 0", vec![0x00, 0x70, 0x00]),
        ("mull a2, a3, a4", vec![0x40, 0x23, 0x82]),
        ("quou a2, a3, a4", vec![0x40, 0x23, 0xc2]),
        ("s32c1i a2, a3, 0", vec![0x22, 0xe3, 0x00]),
    ] {
        assert_eq!(xtensa_core::asm::assemble_one(text, 0).unwrap(), bytes, "{}", text);
    }
}
